// Writes the Terms of Service and Privacy Policy, from
// `lib/core/config/legal_documents.dart`, as Markdown into the vault:
//
//   dart run tool/export_legal.dart [vault GSTApp dir]
//
// Default target: ../Dastavez-memory/GSTApp/01 - Product/Legal/. The Dart
// data is the single source; the Markdown is generated and carries a
// frontmatter saying so. Run it after every change to the documents.
import 'dart:io';

import 'package:gst_bill_app/core/config/legal_documents.dart';

void main(List<String> args) {
  final root = args.isNotEmpty ? args.first : '../Dastavez-memory/GSTApp';
  final dir = Directory('$root/01 - Product/Legal')..createSync(recursive: true);
  for (final d in legalDocuments) {
    final file = File('${dir.path}/${d.title}.md');
    file.writeAsStringSync('---\n'
        'type: legal\n'
        'status: draft\n'
        'area: product\n'
        'last_verified: 2026-10-19\n'
        'generated_from: bahi_app/lib/core/config/legal_documents.dart\n'
        'code_paths:\n'
        '  - bahi_app/lib/core/config/legal_documents.dart\n'
        '  - bahi_app/lib/features/auth/presentation/legal_screen.dart\n'
        '---\n\n'
        '> Generated by `dart run tool/export_legal.dart` in `bahi_app`. Edit the Dart file, not this note.\n'
        '> Up: [[Legal Pages]]\n\n'
        '${legalDocumentToMarkdown(d)}');
    stdout.writeln('wrote ${file.path}');
  }
  final left = legalPlaceholdersLeft();
  if (left.isNotEmpty) stdout.writeln('placeholders still to fill: ${left.join(', ')}');
}
